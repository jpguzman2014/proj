import type { Difficulty, EntityKind, SubEntity } from './types';

/**
 * Sub-entities hang off a game by id. Everything the question engine needs to
 * ask about a character, weapon, enemy, boss, item, vehicle or location lives
 * here; platform, genre and era filters resolve through the owning game, so a
 * new category never needs its own copy of the metadata.
 */
function e(
  kind: EntityKind,
  gameId: string,
  name: string,
  subtype: string,
  difficulty: Difficulty,
  extra: Partial<SubEntity> = {},
): SubEntity {
  const id = `${gameId}:${kind}:${name
    .toLowerCase()
    .replace(/[^a-z0-9]+/g, '-')
    .replace(/(^-|-$)/g, '')}`;
  return { id, kind, gameId, name, subtype, difficulty, ...extra };
}

